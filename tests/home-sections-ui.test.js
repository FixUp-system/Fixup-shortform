// home 은 **결과물로 연다**(2026-09-08 사장님 확정). 그전에는 "만드는 방식 고르기"로 열었다.
// 2026-09-09 에 한 번 더 바뀌었다 — **손님도 같은 화면을 본다**(사장님 확정). 그래서
// 첫 화면이 곧 랜딩이고, 버튼만 신원에 따라 갈린다.
//
// 이 저장소의 화면 계약은 소스 문자열로 잰다 — 렌더 테스트 인프라가 없다.
//
// ★★ 그래서 이 파일의 단정은 **이름이 적혀 있는가**가 아니라 **코드가 그렇게 생겼는가**를
//   잰다. 처음에는 `/thumbUrl/`·`/\/api\/projects/` 처럼 이름만 찾았는데, 실제로 호출을
//   걷어내고 돌려 보니 **초록이었다** — 바로 위 주석이 그 이름을 말하고 있어서다
//   (2026-09-08 변이 검증). 이 저장소는 규칙 위에 이유를 적는 문화라 그 배치가 흔하고,
//   그러면 판이 조용히 "항상 참"이 된다. 주석을 걷어내고 재는 방법도 있지만, 그 제거기는
//   `//   ★ …` 같은 줄에 취약하다는 것이 이미 실측돼 있다(components/ProjectCards.jsx
//   머리말). 그래서 **주석에는 못 나오는 모양**을 직접 잰다.
//
// ★ 화면이 **두 파일**이 됐다(2026-09-09). 껍데기(app/home/page.js)는 서버 컴포넌트라
//   신원을 읽고, 목록을 무는 칸만 클라이언트 부품(components/HomeMade.jsx)이다.
//   전송량 단정은 **둘 다** 봐야 한다 — 한 쪽만 재면 다른 쪽으로 영상이 돌아온다.
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";

const src = readFileSync("app/home/page.js", "utf8");
const made = readFileSync("components/HomeMade.jsx", "utf8");

describe("home 은 결과물로 연다", () => {
  it("★ 최근 완성본을 불러온다", () => {
    // 부르는 자리를 잰다 — 주소를 말만 하는 주석은 통과하면 안 된다.
    expect(made, "목록을 안 부른다").toMatch(/fetch\(\s*["'`]\/api\/projects/);
  });

  it("★★ 목록에서 영상을 물지 않는다 — 표지 그림만 그린다", () => {
    // 2026-09-07 전송량 사고: 목록이 <video> 를 물면 그것만으로 할당량이 탄다.
    //
    // ★ 이 단정만 **날 것 그대로** 잰다(주석까지 센다). 여기서는 주석이 판을 더 엄하게
    //   만든다 — 그 태그 이름이 소스에 적혀 있다는 것 자체가 돌아오는 길목이라,
    //   아예 안 적는 편이 낫다(테마 분기를 세는 판과 같은 규율). 그래서 두 파일의
    //   주석은 "영상 태그"라고만 쓰고 꺾쇠를 붙이지 않는다.
    expect(src, "<video> 가 껍데기에 있다").not.toMatch(/<video/);
    expect(made, "<video> 가 목록에 있다").not.toMatch(/<video/);
    // 표지 그림이 **실제로** 작은 판을 지나는지 본다. `/thumbUrl/` 로만 재면 호출을
    // 걷어내도 주석 한 줄이 단정을 통과시킨다(실측).
    expect(made, "표지 그림이 thumbUrl 을 안 지난다").toMatch(/src=\{thumbUrl\(/);
    expect(made, "thumbUrl 을 안 가져온다").toMatch(/import\s*\{[^}]*\bthumbUrl\b[^}]*\}\s*from/);
  });

  it("★ 완성본이 없으면 결과물 띠를 감춘다 — 빈 격자를 보이지 않는다", () => {
    // 조건이 **그 띠를** 가리는지까지 본다. 어딘가에 `.length > 0` 이 있기만 하면
    // 통과하는 단정은 띠가 무조건 그려져도 초록이다.
    expect(made, "완성본이 없어도 띠를 그린다").toMatch(
      /length\s*>\s*0\s*&&\s*\(?\s*<div className="home-band"/
    );
  });

  it("★★ 카드에 글을 안 싣는다 — 저장된 제목이 프롬프트 원문이다", () => {
    // 2026-09-09 프로덕션 실측: 완성본 여섯 편 중 셋의 제목이
    // "You are creating a premium advertisement image…" 라는 영어 지문 원문이었다.
    // 손님이 보는 첫 화면이므로 그 글자가 그대로 얼굴이 된다. 레퍼런스(dropshot·deevid)도
    // 예시 항목에 글을 안 단다 — 그림만 깐다.
    //
    // ★ 이 파일의 주석에서는 그 낱말을 **영어로 적지 않는다**(아래 단정이 날 것으로 잰다).
    expect(made, "저장된 이름을 카드에 싣는다").not.toMatch(/\btitle\b/);
  });

  it("★ 그림이 안 열리는 칸은 스스로 빠진다", () => {
    // 2026-09-09 프로덕션 실측: 표지 주소가 있는 25편 중 **5편만** 실제로 열린다
    // (09-07 파일 미이관). 주소가 있는지만 보고 실으면 첫 화면이 빈 칸으로 찬다.
    expect(made, "못 받은 그림을 그대로 둔다").toMatch(/onError=\{/);
  });

  it("★ 보관함으로 가는 길이 있다 — 손님의 첫 화면이 막다른 길이면 안 된다", () => {
    // 2026-08-27 사장님 지시("기본으로 보관함 바로 확인")를 첫 화면이 바뀌어도 지킨다.
    expect(made, "더 보기가 없다").toMatch(/href="\/archive"/);
  });

  it("★ 주 버튼의 문이 신원에 따라 갈린다", () => {
    // 손님에게는 가입의 문을, 이미 들어온 사람에게는 만드는 문을 준다.
    //
    // ★★ 처음에는 `/signedIn\s*\?/` 와 두 주소가 **있는지**만 셌는데, 버튼의 href 를
    //   `"/login"` 으로 못 박아도 **초록이었다**(2026-09-09 변이 검증). 같은 파일 안의
    //   버튼 **글자** 삼항과 도구 표의 `path: "/ads/new"` 가 그 셋을 대신 통과시킨다.
    //   이 저장소의 판이 조용히 "항상 참"이 되는 바로 그 모양이라, **문 자체가 갈리는지**를
    //   한 덩어리로 잰다.
    expect(src, "주 버튼의 문이 신원을 안 본다").toMatch(
      /href=\{signedIn\s*\?\s*"\/ads\/new"\s*:\s*"\/login"\}/
    );
    // 실제 버튼에 달려 있어야 한다 — 주석에는 JSX 가 통째로 들어올 일이 없다.
    expect(src, "주 버튼이 없다").toMatch(/<[a-zA-Z][\w-]*\s[^>]*className="cta"/);
  });

  it("★ 도구 격자가 세 갈래를 모두 연다", () => {
    // 표(TOOLS)의 path 칸을 잰다 — 주석에 적힌 주소로는 못 지난다.
    // ★ `/ads`·`/reel` 에는 화면이 없다(app/ads/new · app/reel/new 만 있다). 그래서
    //   뿌리로 시작하는지만 보고 끝까지 못 박지 않는다 — 못 박으면 문이 옮겨갈 때마다
    //   이 판이 화면과 함께 두 벌로 갈린다.
    for (const path of ["/ads", "/create", "/reel"]) {
      // ★ String.raw 다 — 보통 템플릿 문자열에서는 `\s` 가 그냥 `s` 로 죽어
      //   `path:s*"…` 라는 영원히 안 맞는 단정이 된다(2026-09-09 에 실제로 밟았다).
      expect(src, `${path} 로 가는 길이 없다`).toMatch(
        new RegExp(String.raw`path:\s*"${path}`)
      );
    }
    // 표를 만들어 놓고 안 쓰면 아무 데도 못 간다.
    expect(src, "표의 path 를 링크에 안 건다").toMatch(/href=\{t\.path\}/);
  });

  it("★ 만드는 방법은 세 걸음이다", () => {
    // 레퍼런스 둘 다 3단이다. 넷째 칸이던 "보관함"은 만드는 방법이 아니라 결과라 뺐다.
    const ns = src.match(/n:\s*"\d\d"/g) || [];
    expect(ns.length, "걸음 수가 셋이 아니다").toBe(3);
  });

  it("★ 전시층은 여기서만 쓴다", () => {
    // ★★ 2026-09-08(Task 5) — 이 파일의 다섯 단정 중 **이것만** 이름만 재고 있었다.
    //   `/className="display"/` 는 이 줄을 설명하는 **주석 한 줄**로도 통과한다(이 화면의
    //   머리말이 실제로 전시층을 언급한다). 그래서 **여는 태그까지** 요구한다 — 주석에는
    //   JSX 가 통째로 들어올 일이 없다.
    //   ★ 태그 이름은 못 박지 않는다(h1 이 h2 로 바뀌는 것은 결함이 아니다). 못 박는 것은
    //     "실제 원소에 달려 있다"까지다.
    expect(src, "display 제목이 없다 — 주석 말고 실제 태그에 달려 있어야 한다").toMatch(
      /<[a-zA-Z][\w-]*\s+className="display"/
    );
  });
});
