// 완성 화면에는 **값 드는 문을 두지 않는다** — 돌아갈 길을 둔다.
//
// 사장님 지시(2026-08-18): "보관함에서 광고 영상 페이지로 이어서 작업하기를 눌렀을 때
// 완성된 영상은 [다시 만들기 · 35크레딧]으로 표현되어 있는데, 이 버튼 제외하고
// **이전 단계로 돌아가기** 버튼 만들어줘."
//
// 완성 화면은 사장님이 **결과를 확인하는 자리**다. 거기 놓인 [다시 만들기]는 누르는 순간
// 정가가 통째로 다시 나가는 문인데, 완성본을 보러 들어온 손이 가장 먼저 닿는 자리에 있었다.
// 게다가 보관함에서 "이어서 작업하기"로 들어온 사장님이 원하는 것은 대개 **고치는 것**이고,
// 고치는 자리는 다시 만들기가 아니라 **시나리오**다.
//
// ★ 다시 만드는 길이 사라지는 것은 아니다 — 시나리오로 돌아가면 거기 [다시 쓰기]가 있고,
//   고친 뒤에 만들면 그때 값을 낸다. 즉 **값을 내기 전에 무엇을 바꿀지 정하는 순서**가 된다.
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";

const ad = readFileSync("app/ads/[id]/page.js", "utf8");
const done = ad.slice(ad.indexOf('{view === "done" && video && ('), ad.indexOf('{!handled && ('));

describe("광고 완성 화면 — 무엇을 누를 수 있나", () => {
  it("★★ 유료로 다시 만드는 문이 없다", () => {
    expect(done, "완성 화면에 [다시 만들기]가 남아 있다").not.toMatch(/다시 만들기/);
    expect(done, "완성 화면에서 유료 생성을 시작한다").not.toMatch(/startRender/);
    // 값 표기도 함께 사라져야 한다 — 누를 수 없는 값을 적어 두면 무엇을 뜻하는지 모른다
    expect(done, "값 표기가 남아 있다").not.toMatch(/showCredits/);
  });

  it("★★ 이전 단계로 돌아가는 길이 있다", () => {
    expect(done, "돌아갈 길이 없다").toMatch(/이전 단계/);
    // 광고 흐름에서 완성의 앞 단계는 시나리오다 — 거기서 고치고 다시 만든다
    expect(done, "시나리오로 안 보낸다").toMatch(/step=scenario/);
  });

  it("★ 내려받기는 그대로다 — 값이 안 드는 일이다", () => {
    expect(done, "내려받기가 사라졌다").toMatch(/내려받기/);
    expect(done, "내려받기 표시가 바뀌었다").toMatch(/dl=1/);
  });

  it("★ 완성본 재생도 그대로다", () => {
    expect(done, "미리보기가 사라졌다").toMatch(/preview-video/);
  });
});
