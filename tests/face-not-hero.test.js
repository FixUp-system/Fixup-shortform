// **장면 지문이 사람을 제대로 담는다.**
//
// ★★★ **2026-09-03 뒤집힘 — 얼굴 제한을 걷었다**(사장님 결정). 이 파일은 원래
//   *"얼굴이 주인공이 되지 않게 쓴다 — 초상 거절을 애초에 안 부른다"*(2026-08-31)를
//   지키는 판이었다. 아래 옛 서사는 **지우지 않고 기록으로** 둔다 — 되돌릴 날이 오면
//   그때 필요한 것이 바로 그 근거이기 때문이다.
//   걷은 근거(전부 실측):
//   · **그 제한을 켠 채로** 09-03 오후에 초상 거절이 **3연속** 났다. 제한은 얼굴을 작게
//     할 뿐 없애지 못한다 — 그 판에는 칸마다 얼굴이 2~3개 있었다.
//   · 최근 프로젝트 40건 중 **초상 거절 상태가 0건**이고, 거절 흔적(`face_safe`)은 3건인데
//     전부 08-31~09-02 — **격자가 없거나 틀렸던 시절**이다. 09-03 16:13 에는 2.5 단계별
//     편이 거절 없이 완성됐다.
//   · 실제로 막는 일은 굽기 직전의 **얼굴 격자**(lib/reel/face-grid.js)가 한다.
//   · 제한이 치른 값은 확실했다 — 팔만 나온 컷, 다섯 장면이 전부 제품컷만 된 판(57db7ad6).
//   ⚠️ 되돌릴 때 먼저 물을 것은 "제한을 다시 걸까"가 아니라 **"격자가 왜 못 막았나"**다.
//
// ───────────────── 아래는 2026-08-31 당시의 기록이다 ─────────────────
//
// ★★★ 실측으로 터졌다. 볶음밥 소재인데 시나리오가 5번 장면에 사람을 넣었다:
//   *"a cheerful young woman **facing camera, eyes bright**, holding the heaped spoon
//   just at her lips, **mid-bite smile**"* → 통짜가 그 판을 참조로 넘기자 **422**:
//   `loc:["body","image_urls"]` — *"likenesses of real people…"*
//
// ★★ 왜 웹의 영상에는 얼굴이 나오는데 우리는 막히나 — **검사 대상이 출력이 아니라 입력**이다.
//   텍스트로만 만들면(t2v) 참조 이미지가 없어 이 검사가 안 걸린다. 우리는 참조를 넘기므로
//   (i2v·r2v) 훨씬 빡빡하다: 참조로 실제 사람 사진을 주면 딥페이크가 되기 때문이다.
//   **분류기는 그 얼굴이 AI 가 그린 것인지 구별하지 않는다** — 프롬프트로 "AI 인물"이라고
//   적어도 안 닿는다(2026-08-25 실측).
//
// ★ **완전 금지가 아니다.** 같은 날 실측에 *실사인데 통과한* 표본이 있었다 — 눈을 감고
//   측면광이었다. 기준은 **식별 가능성**(크기 × 정면성 × 응시)이다.
//
// ★★ 그래서 지문이 부딪히던 자리를 고친다. 그전에는 이렇게만 적혀 있었다:
//   *"id 를 적었으면 그 장면의 shows 는 **얼굴이 보이게** 쓴다"* — 인물 사진이 쓰이게 하려는
//   규칙인데(손만 그리면 그 사진이 안 쓰인다), 그 말만 있으니 모델이 정면 클로즈업을 썼다.
//   **사람을 빼라는 뜻이 아니다** — 얼굴이 주인공이 되지 않게 쓰라는 뜻이다.
import { describe, it, expect } from "vitest";
import { readFileSync } from "node:fs";
import { classifyFailure } from "../lib/failure.js";

const src = readFileSync("lib/reel/scenario.js", "utf8");

describe("장면 지문 — 얼굴이 주인공이 되지 않게", () => {
  // ★★★ 2026-09-03 — **금지를 지키던 판 셋을 허용을 지키는 판으로 뒤집었다.**
  //   금지가 조용히 되살아나면 팔만 나오는 컷도 함께 돌아오므로, 부재를 판이 지킨다.
  //   ★ 지우지 않은 이유: 되돌리는 것은 한 줄이지만, **왜 걷었는지를 잃으면** 다음 사람이
  //     거절 한 번에 놀라 그대로 다시 건다(그러면 같은 자리를 세 번째 돈다).
  it("★★★ 얼굴이 보여도 된다고 **명시적으로** 말한다", () => {
    expect(src, "얼굴을 여는 말이 없다").toMatch(/얼굴이 보여도 된다/);
  });

  it("★★★ 정면 응시·얼굴 클로즈업을 **막지 않는다**", () => {
    // ★ 무엇을 신호로 삼나. 이 파일과 지문에는 걷은 이유를 적느라 **옛 금지문이 과거형으로
    //   인용**돼 있다 — 그 인용까지 잡으면 판이 자기 설명을 위반으로 센다(실제로 그랬다).
    //   그래서 옛 규칙의 **작동 문장**을 잡는다: 영어 낱말 목록을 주고 "쓰지 않는다"로
    //   닫던 그 한 줄이 금지를 실제로 집행하던 자리다.
    expect(src, "옛 금지문(영어 낱말 목록 + '쓰지 않는다')이 되살아났다")
      .not.toMatch(/같은 말을 쓰지 않는다/);
    // 그리고 막는 것의 수는 하나로 남아 있어야 한다(둘·셋으로 늘면 얼굴 금지가 돌아온 것이다).
    expect(src).toMatch(/막는 것은 하나뿐이다/);
  });

  it("★★ 왜 걷었는지가 지문 안에 남아 있다 — 근거를 잃으면 다음 사람이 다시 건다", () => {
    expect(src).toMatch(/얼굴 제한을 걷었다/);
    expect(src).toMatch(/face-grid/);
  });

  it("★★ **사람을 빼라고는 안 한다** — 인물이 나오는 영상은 계속 만들 수 있어야 한다", () => {
    // 인물 사진(avatar)을 고르는 규칙이 그대로 살아 있어야 한다. 얼굴을 통째로 막으면
    // 캐스팅이 죽고, "사람이 말한다" 컨셉이 통째로 사라진다.
    expect(src).toMatch(/avatar_id/);
    expect(src, "사람을 아예 넣지 말라고 시킨다").not.toMatch(/사람을 넣지 마라|인물을 넣지 마라/);
  });

  it("★ 왜 그런지도 적어 둔다 — 규칙만 있으면 다음 사람이 지운다", () => {
    expect(src).toMatch(/초상|거절/);
  });

  // ★★★ 2026-08-31 사장님 결정 **B** — 금지형에서 **긍정형**으로 옮겼다.
  //   그전 문장에도 "사람을 빼라는 뜻이 아니다"가 있었는데도 모델은 안전한 쪽으로 도망쳤다:
  //   같은 날 실측(57db7ad6)에서 성공한 편은 **다섯 장면이 전부 제품컷**이었다.
  //   사장님 걱정이 그것이다 — *"인물이 제품을 사용하는 게 자연스러운데 의도적으로 피해서
  //   어색해질까봐"*. 그래서 **되는 그림을 먼저, 예시로** 적는다.
  describe("긍정형 — 되는 쪽을 먼저 말한다", () => {
    it("★★ 권장 프레이밍을 **예시로** 준다 — 뭉뚱그린 허용은 안 먹는다", () => {
      for (const shot of [/웃거나 말하는 얼굴/, /손/, /상반신|가슴 위/, /옆모습|어깨너머/]) {
        expect(src, `권장 예시가 없다: ${shot}`).toMatch(shot);
      }
    });

    it("★★★ 사람을 통째로 빼는 것을 **명시적으로** 막는다", () => {
      expect(src).toMatch(/사람을 빼지 마라/);
    });

    // ★ 2026-09-03 — 셋이 됐다. 보탠 ③은 얼굴 회피가 아니라 **몸의 일관성**이다
    //   (몸은 뒤에 있는데 팔만 앞으로 들어오는 화면). 얼굴 규제를 나중에 풀더라도
    //   ③은 남는다 — 오히려 얼굴을 담게 되면 "사람을 사람으로 담아라"가 그 답이다.
    it("★ 막는 것을 **세어서** 못 박는다 — 제약이 들리는 것보다 좁다", () => {
      expect(src).toMatch(/막는 것은 하나뿐이다/);
    });

    it("★★ 몸은 뒤에 있는데 팔만 앞으로 들어오는 화면을 막는다(2026-09-03 사장님 지적)", () => {
      expect(src).toMatch(/팔·손만 앞으로 들어오는 화면/);
      // 둘 중 하나로 정하라는 **대안**이 함께 있어야 한다 — 금지만 적으면 사람이 사라진다.
      expect(src).toMatch(/몸을 아예 프레임 밖에 둔다/);
    });

    it("★ 사람이 제품을 쓰는 장면을 **쓰라고** 한다(피하라가 아니다)", () => {
      expect(src).toMatch(/사람이 제품을 쓰는 장면을 써라/);
    });
  });
});

describe("거절 문구 — 두 경우를 다 가리킨다", () => {
  const RAW = '영상 생성 실패 (422) {"detail":[{"loc":["body","image_urls"],"msg":"The images or videos provided may contain likenesses of real people or other private information that cannot be processed.","type":"content_policy_violation"}]}';

  it("★★ 우리가 그린 장면일 수도, 올린 사진일 수도 있다 — 둘 다 말해 준다", () => {
    // 그전 문구는 *"그 사진을 빼고 다시 시도해 주세요"* 뿐이었다. 단계별 통짜에서는
    // 걸리는 것이 **우리가 그린 스토리보드**라, 사장님이 할 수 없는 조언이었다.
    const { message } = classifyFailure(RAW);
    expect(message, "장면을 고치라는 길이 없다").toMatch(/장면|시나리오/);
    expect(message, "사진을 바꾸라는 길이 없다").toMatch(/사진/);
  });

  it("갈래와 재시도 가능 여부는 그대로다", () => {
    const c = classifyFailure(RAW);
    expect(c.code).toBe("rejected_likeness");
    expect(c.retryable).toBe(true);
  });
});
