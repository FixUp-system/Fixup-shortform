const trim = (v) => (typeof v === "string" ? v.trim() : "");

// 이 영상이 무엇을 위한 것인가 — **대본이 겨눌 과녁**이다.
//
// 브리핑의 takeaway 가 원천이고, 이 함수는 그것이 비었을 때의 마지막 그물이다.
