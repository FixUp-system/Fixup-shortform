// ⚠️ 지금 이 함수를 부르는 곳은 없다(2026-08-16) — 목적을 [목적] 블록으로 실어 보내던
//   대본 프롬프트가 사라졌고, 시나리오 지문은 자료 원문을 직접 읽는다. 목적을 다시 지문에
//   실을 때 이 폴백이 살아 있어야 해서 판정만 남겨 뒀다(tests/script-purpose.test.js).
const PURPOSE_BY_MODE = {
  물건: "이 물건을 갖고 싶어지게 — 무엇이 좋은지가 눈에 보이게",
  사람: "이 사람을 믿게 — 무엇을 하는 사람인지가 남게",
  정보: "이 내용을 이해하고 행동하게 — 무엇을 하면 되는지가 남게",
};
const PURPOSE_FALLBACK = "보고 나서 무엇이 좋은지 한 가지가 또렷이 남게";

export function purposeOf(project) {
  const said = trim(project?.briefing?.takeaway);
  if (said) return said;
  return PURPOSE_BY_MODE[project?.briefing?.focus?.mode] || PURPOSE_FALLBACK;
}
