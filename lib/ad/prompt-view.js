// 영상 프롬프트를 **읽을 수 있게** 끊는다 — 화면 전용, 값은 안 바꾼다.
//
// ★★ 왜 필요한가(2026-08-27 사장님 지적): Fable 이 낸 프롬프트가 3,785자인데 줄바꿈이
//   **0개**였다. 시나리오 화면은 사장님이 그 글을 읽고 [이대로 만들기]를 누를지 정하는
//   자리인데, 한 문단이면 읽을 수가 없어서 그 자리가 죽는다.
//
// ★ 근본 처방은 지문이다 — AD_SYSTEM 이 "단마다 줄을 바꾼다"를 시킨다. 이 파일은 **그
//   전에 만든 시나리오**를 위한 것이다. 옛 문서도 열어서 읽을 수 있어야 한다.
// ★ 줄바꿈이 이미 있으면 **손대지 않는다** — 모델이 나눈 대로가 가장 정확하다.
//
// ⚠️ 이 파일은 화면("use client")이 import 한다. **import 문을 두지 마라** —
//    사슬 끝에 fs 가 딸려 오면 빌드가 깨진다(이 저장소가 세 번 겪은 사고다).

// 단 머리말 — 대문자 낱말이 이어지다 콜론이나 여는 괄호로 끝나는 자리.
//   REFERENCE IMAGE:  ·  PEOPLE:  ·  SCENES AND NARRATION (  ·  CAMERA, LIGHT, COLOR:
//   SOUND:  ·  NEGATIVE:
//
// ★ 머리말을 **통째로 잡는다**(앞을 내다보기만 하지 않는다). 앞만 보면 "REFERENCE IMAGE:"
//   의 **가운데**("IMAGE:" 앞)에서도 조건이 맞아 한 머리말이 두 줄로 갈린다 — 실제로 그렇게
//   깨졌다. 통째로 잡으면 그 자리가 이미 소비돼 안쪽에서 다시 안 걸린다.
// ★ 한 글자 대문자(문장 첫 글자 "A ...")는 안 걸린다 — 낱말마다 두 글자 이상을 요구한다.
const SECTION = /\s+((?:[A-Z][A-Z&]+)(?:[ ,]+[A-Z][A-Z&]+)*)(?=\s*[:(])/g;

// 장면 시간 구간 — (0-4s) · (0–4s) · (12–15s). 하이픈과 en dash 둘 다 받는다.
const SCENE_AT = /\s+(?=\(\d+\s*[-–—]\s*\d+\s*s\))/g;

// 화면에 보여 줄 모양으로 끊는다. **원문을 바꾸지 않는다** — 공백을 줄바꿈으로 바꿀 뿐이다.
export function prettyPrompt(text) {
  const t = typeof text === "string" ? text : "";
  if (!t.trim()) return "";
  // 모델이 이미 나눠 놓았으면 그대로 둔다.
  if (t.includes("\n")) return t;
  return t.replace(SECTION, "\n\n$1").replace(SCENE_AT, "\n");
}
