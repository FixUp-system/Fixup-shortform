// 연 자리로 돌아와 닫는다. **짧은 편에는 걸지 않는다** — 15초는 목표 83자에 컷 2개라,
// 강제하면 문장 넷 중 둘이 같은 얘기가 된다(사용자 결정 2026-08-13).
//
// ★ SYSTEM·REWRITE_SYSTEM·EDIT_SYSTEM 상수에는 넣지 않는다. 상수는 길이를 모르므로
//   넣는 순간 15초짜리에도 걸린다. 지문(동적 user 내용)에 조건부로 붙인다.
// ★ 문구는 여기 한 자리뿐이다. 세 지문이 각자 적으면 언젠가 갈라진다.
//
// ★ 이 값은 **밀도 반영 전(pre-density) 자수**로 적혀 있다 — SPEECH_DENSITY 가 생기기 전에
//   15초=83자 · 30초=165자로 잰 경계다. targetChars 가 이제 SPEECH_DENSITY 를 곱해 나오므로,
//   wantsBookend 에서 이 값과 targetChars 를 나란히 비교하려면 이 상수 쪽도 같은 배수로
//   내려야 한다(아래 wantsBookend 참고) — 안 그러면 30·45초까지 조용히 수미상관을 잃는다.
export const BOOKEND_MIN_CHARS = 120;

// 고른 초가 아니라 **목표 자수**로 잰다 — 사장님이 길이를 안 고르면(자동) 자료가 길이를
// 정하므로, 고른 초만 보면 자동 모드가 통째로 빠진다.
// 15초=83자 · 30초=165자라 경계 120이 그 사이에 있다(밀도 반영 전 기준).
//
// ★ targetChars 는 이제 SPEECH_DENSITY 를 곱해 돌려주므로, BOOKEND_MIN_CHARS(밀도 반영 전
//   자수)를 그대로 비교하면 30·45초까지 경계 아래로 내려가 수미상관이 아무 길이에도 안 걸린다.
//   양쪽을 같은 배수로 내려 비교해야 밀도 계수 도입 전과 같은 프로젝트가 같은 판정을 받는다.
export function wantsBookend(project) {
  return targetChars(project) > BOOKEND_MIN_CHARS * SPEECH_DENSITY;
}

