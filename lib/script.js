// 사장님이 고를 수 있는 길이. 숏폼의 실제 폭에 맞춘 네 칸이다.
export const TARGET_CHOICES = [15, 30, 45, 60];

// ★ 말의 밀도 — **영상 길이를 말로 다 채우지 않는다.**
//
// 근거는 광고 3편 전수 확인이다(2026-08-14): 15초 주문에 대사가 31~39자(밀도 37~47%)뿐이고
// 나머지는 화면과 소리가 채웠다. 4초 장면에 "하루의 끝, 지친 피부에게."(12자 = 2.2초)를
// 싣고 1.8초는 펌프 클릭음과 피아노다.
//
// 분할생성은 컷 초 = 그 문장의 낭독 시간이라 **정의상 밀도 100%** 였다 — 쉬는 자리가
// 구조적으로 없었고, 그것이 "그냥 정보를 읽는 느낌"의 뿌리다.
//
// ⚠️ 표본이 광고 3편뿐이라 임계값 근거로는 얇다(이 저장소 규율: 임계는 실측 분포에서 뽑는다).
//    실측 범위 37~47% 의 가운데인 45% 로 시작하고, **분할생성 실측이 쌓이면 다시 뽑는다.**
//    값을 바꾸는 곳이 여기 하나뿐이라 다시 뽑는 비용은 작다.
export const SPEECH_DENSITY = 0.45;

// 목표 분량.
// 사장님이 길이를 골랐으면 그것이 목표다 — 10초를 고른 사람에게 5초를 주면 실패다.
// 고르지 않았으면(자동) 자료가 담은 사실 수로 정한다. 사실 하나에 30자 남짓,
// 상한 220자는 40초(숏폼 상한), 하한 60자는 11초.
// 어느 쪽이든 이 숫자 하나가 원고 길이를 쥔다 — 장면별로 초를 배분하던 때 총합이 흔들리던 자리다.
// ★ 어느 갈래든 SPEECH_DENSITY 를 곱한다 — 영상 길이(초)를 말로 다 채우지 않는다.
export function targetChars(project) {
  const chosen = project?.settings?.target_seconds;
  if (TARGET_CHOICES.includes(chosen)) {
    return Math.round(chosen * CHARS_PER_SEC * SPEECH_DENSITY);
  }
  return Math.round(materialChars(project) * SPEECH_DENSITY);
}

// 자료가 감당하는 분량 — 사장님이 무엇을 고르든 이 값은 자료만 본다.
// 고른 길이와 이 값을 나란히 보여줘야 "왜 짧게 나왔는지"를 만들기 전에 안다.
function materialChars(project) {
  return Math.min(220, Math.max(60, factCount(project) * 30));
}

// 지금 자료로 만들 수 있는 길이 — 사실 하나에 약 5초.
// 사장님에게 "자료를 더 주면 영상이 길어진다"를 숫자로 보여주는 자리다.
export function capacitySeconds(project) {
  return Math.max(1, Math.round(materialChars(project) / CHARS_PER_SEC));
}

