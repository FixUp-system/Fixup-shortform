// 사장님의 한국어 수정 지시로 **프롬프트 본문을 다시 쓴다** — 뒤에 덧붙이지 않는다.
//
// 왜(2026-08-18 사장님 지시): 지금까지 수정 지시는 꼬리에 한 줄로 덧붙었다.
//   `… Important correction requested by the user, apply it strictly: 배경을 노을로.`
// 그러면 **원래의 배경 서술이 그대로 남은 채** 새 요구가 뒤에 붙어 모델이 서로 다투는 두
// 지시를 받는다. 그리고 컷에 지시가 하나만 저장돼 다음 재생성 때 덮인다 — 쌓이지 않는다.
//
// 사장님이 실제로 쓰는 말은 이런 모양이다:
//   "지금 사진에서 어떤 이미지를 고치고 싶어. 이 이미지를 수정하고, 배경을 수정해줘"
// 한 문장에 **고칠 것과 더할 것이 섞여** 들어온다. 그래서 규칙이 셋이다:
//   ① 지시가 가리키는 부분은 **바꾼다**
//   ② 지시에만 있는 새 요구는 **더한다**
//   ③ ★ **나머지는 글자 그대로 둔다** — 이것이 없으면 매번 통째로 다시 쓰여, 사장님이
//      고치지도 않은 부분이 흔들리고 무엇이 왜 바뀌었는지 아무도 설명할 수 없다.
//
// ★ 이 파일은 **메시지 조립만** 한다(순수). LLM 호출은 부르는 쪽이 한다 — 이 저장소가
//   프롬프트 조립과 호출을 가르는 방식 그대로다(lib/cuts.js buildShowsMessages 와 같은 결).
//
// ★ 결과는 컷별 덮어쓰기(image_prompt·clip_prompt)로 저장된다. 그래서 사장님이 접힌 칸에서
//   **바뀐 프롬프트를 눈으로 확인**할 수 있고, 각인이 그 값을 보므로 낡음 판정도 따라온다.

// 지시 길이 상한. 통짜 문서를 붙여 넣으면 LLM 값이 튀고, 무엇보다 그 글이 프롬프트가 되면
// 컷 프롬프트 상한(lib/costs.js LEDGER_PROMPT_MAX)에 걸린다.
export const REVISE_MAX = 500;

const RULES = `너는 이미 만들어진 **영상용 그림 지시문**을 사장님의 요구대로 고친다.

지켜야 할 것:
- 사장님이 **가리킨 부분만 고친다.** 지시에 없는 문장·낱말은 **글자 그대로 그대로 둔다** —
  고치지 않은 부분이 흔들리면 사장님은 무엇이 왜 바뀌었는지 알 수 없다.
- 지시에만 있는 **새 요구는 더한다.** 원래 지시문에 없던 것이면 자연스러운 자리에 붙인다.
- 사장님 요구가 원래 문장과 부딪히면 **사장님 쪽을 따른다**(원래 문장을 지우거나 바꾼다).
- 화면에 **글자를 넣으라고 요구하지 마라.** 자막·로고는 우리가 나중에 따로 붙인다.

답하는 형식 — **JSON 하나만** 낸다:
{"prompt": "고쳐 쓴 지시문 전체 (영어)"}

★ 이 형식이 계약이다. 받는 쪽(lib/llm.js callJson)이 응답 전체를 JSON.parse 하고
  "prompt" 칸만 읽는다 — 맨 글로 답하면 파싱이 던져 **고쳐 쓴 결과가 통째로 버려지고**
  값만 나간다(2026-08-19 실측: 그 상태로 한 번도 성공한 적이 없었다).
★ "prompt" 값 **안**에는 지시문 한 덩어리만 담는다. 설명·머리말·목록을 담지 마라 —
  담으면 그 글자까지 그대로 그림 모델에 실린다.`;

const CLIP_RULES = `
- 이 지시문은 **움직임**을 말한다(무엇이 어떻게 움직이는가). 그림의 내용을 새로 그리라고
  하지 마라 — 첫 프레임은 이미 만들어진 그림이다.
- **대사·목소리를 건드리지 마라.** 그 글자는 자막으로도 나가므로(우리가 원고를 화면에 태운다)
  여기서 고치면 들리는 말과 화면의 자막이 갈린다.`;

// 부를 메시지를 만든다. 만들 것이 없으면 **null** 이다 — 부르는 쪽이 값 드는 호출을
// 아예 안 만들게 하기 위해서다(빈 지시로 LLM 을 부르면 돈만 나가고 결과는 같다).
export function buildPromptReviseMessages({ current, instruction, kind = "image" } = {}) {
  const now = typeof current === "string" ? current.trim() : "";
  const want = typeof instruction === "string" ? instruction.trim() : "";
  if (!now || !want) return null;
  if (want.length > REVISE_MAX) {
    throw new Error(`수정 지시는 ${REVISE_MAX}글자까지예요 (지금 ${want.length}글자).`);
  }
  const system = kind === "clip" ? RULES + CLIP_RULES : RULES;
  return {
    system,
    user: `지금 지시문:\n${now}\n\n사장님 요구:\n${want}`,
  };
}
