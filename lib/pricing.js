// 모델을 모른다는 것은 이 기능 전에 만들어진 프로젝트라는 뜻이고, 그것들은 Kling 으로 돈다.
// (같은 규칙이 lib/clip-limits.js 의 LEGACY_I2V_MODEL 에 있다. 이 파일은 import 를 둘 수
