// 예산 가드가 뚫린다 — costs.js 그 줄의 주석 참고). 여기 근거를 적을 때도 그 값을 쓴다.
// 1080p·480p 는 **계산값**이다 — 원가가 픽셀수(가로폭 제곱)에 비례한다는 관측에서 왔다
// (광고 t2v 실측 0.682/0.3034 = 2.248 vs 1080²/720² = 2.25). 실청구와 어긋나면 이 표를 고친다.
