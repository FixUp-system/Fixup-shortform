//
// ★★ 원가비와 **크레딧 값**은 다른 규칙이다 — 헷갈리기 쉬우니 갈라서 적는다.
//   · 1080p 는 원가비 2.25 를 **그대로** 썼다(160 × 2.25 = 360, 딱 떨어진다).
//   · 480p 는 원가비가 4/9(≈0.444)지만 그대로 쓰면 36/71/107/142 가 나온다. 이 저장소의
//     가격표는 전부 5·10 단위의 깔끔한 숫자라(25/50/75/100 · 80/160/240/320) 그 관례에
