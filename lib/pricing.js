// ★ 크레딧은 **개수**다 — 0.7 크레딧으로 살 수 있는 것이 없고, 화면에 "24.4 크레딧
// 차감"이 뜨면 사장님은 그것이 무슨 뜻인지 모른다. 원가에서 값을 다시 뽑다 보면 소수가
// 떨어지는데(원가 $1.47 ÷ $0.06 = 24.5), 그때 **반올림해서** 정수로 내보낸다
// (2026-08-13 사용자 결정).
//
// 표를 정수로 지키는 것만으로는 부족하다 — 원가가 바뀌어 누가 24.4 를 적어 넣는 날 그
// 소수가 그대로 장부에 들어가고 잔액이 소수가 된다. **나가는 자리**에서 막는다.
// 올림도 버림도 아닌 반올림인 이유: 어느 한쪽으로만 기울면 값이 조금씩 어긋난다.
const credits = (n) => Math.round(Number(n) || 0);

// 길이를 모르거나 목록 밖이면 30초 값으로 본다 — 프로젝트의 target_seconds 는
// null 일 수 있고(사장님이 안 고른 경우) 그때 실제로 만들어지는 분량이 그 언저리다.
export function videoPrice(seconds, model, resolution) {
  const byRes = VIDEO_PRICE[priceModel(model)];
  // 모르는 해상도·해상도를 안 받는 모델은 720p 열로 떨어진다. 던지지 않는 이유는
  // 이 함수를 화면이 부르기 때문이다 — 값이 틀리는 것보다 화면이 사라지는 것이 나쁘다.
  const table = byRes[resolution] || byRes[PRICE_DEFAULT_RESOLUTION];
  const p = table[Number(seconds)];
  return credits(typeof p === "number" ? p : table[30]);
}

// 화면에 적는 말. 0 은 "0 크레딧"이 아니라 **무료**다 — 숫자만 적으면 값이 붙은 것처럼
// 읽힌다. 문구를 여기 두는 이유는 세 화면(③목소리·④이미지·⑤영상)이 같은 말을 해야 하기
// 때문이다. 화면마다 적으면 언젠가 한 곳만 바뀐다.
export function priceLabel(credits) {
  return credits > 0 ? `${credits} 크레딧` : "무료";
}

// priorCount = 이 컷에서 이미 한 재생성 횟수. 0 이면 첫 번째라 공짜다.
// 모르는 종류는 던진다 — 오타로 조용히 공짜가 되는 것이 이 표에서 가장 위험하다.
// 클립만 넷째 인자(해상도)를 탄다. 생략·모르는 값·해상도를 안 받는 모델은 videoPrice 와
// 같은 규칙으로 720p 칸에 떨어진다(여기도 화면이 부르는 자리라 던지지 않는다).
export function regenPrice(kind, priorCount, model, resolution) {
  const entry = REGEN_PRICE[kind];
  if (entry === undefined) throw new Error(`모르는 재생성 종류: ${kind}`);
  let p = entry;
  if (typeof p !== "number") {
    // priceModel 은 VIDEO_PRICE 를 보고 고른다 — 두 표가 갈리면(한쪽에만 모델을 더하면)
    // 여기가 undefined 가 되고 다음 줄이 TypeError 다. 이 함수는 화면(⑤영상)이 부르는
    // 자리라 던지면 페이지가 통째로 안 뜬다 — videoPrice 와 같은 원칙으로 옛 모델까지
    // 한 겹 더 받는다. (갈린 것 자체는 tests/pricing.test.js 의 대조가 잡는다.)
    const byRes = p[priceModel(model)] || p[LEGACY_MODEL];
    p = byRes[resolution] ?? byRes[PRICE_DEFAULT_RESOLUTION];
  }
  return Number(priorCount) >= FREE_REGEN_PER_CUT ? credits(p) : 0;
}

