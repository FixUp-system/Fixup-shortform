// 응답을 보낸 뒤에도 계속 돌아야 하는 일을 **플랫폼에 알린다**.
//
// 왜 필요한가(2026-08-18 프로덕션 실측): 이 저장소의 생성 라우트 여섯은 파이프라인을 `await`
// 없이 띄우고 곧바로 응답한다(서버리스라 응답이 먼저 나가야 한다). 그런데 Vercel 에서 **응답
// 후의 작업은 보장되지 않는다** — `after()`(또는 `waitUntil()`)로 함수 수명을 그 약속까지
// 늘려야 한다. 그것이 없어서:
//   · 클립 3개를 **결제하고 2개만 저장됐다**(오류 기록조차 없다 — catch 도 안 돌았다)
//   · 합성은 두 번 시도해 두 번 다 `render`·`render_error` 가 **둘 다 비었다**
//   · 폴링이 우연히 그 인스턴스를 깨우면 진행되고 아니면 멈췄다 — **부분 성공과 전면 실패를
//     가른 것이 운이었다**
//
// ★ **약속(promise)을 받는다 — 콜백이 아니다.** 콜백을 받으면 파이프라인이 요청 범위 **밖**에서
//   시작하고, 비용 주체는 AsyncLocalStorage 에서 읽으므로(lib/actor.js) 컨텍스트가 없으면
//   `costActor()` 가 **던진다**. 부르는 쪽이 요청 안에서 파이프라인을 시작하고 그 약속만
//   여기 넘기면 컨텍스트가 그대로 따라간다.
//
// ★ 판정을 **한 자리**에 두는 이유: 라우트 여섯이 각자 `after` 를 부르면, 요청 범위 밖에서
//   던지는 성질을 여섯 곳에서 따로 다뤄야 한다(그리고 한 곳이 빠지면 그 라우트만 죽는다).
//
// ⚠️ 상한은 여기서 정하지 않는다 — `maxDuration` 은 **라우트마다** 일의 길이가 달라서
//    라우트에 적는다(Next 는 그 값을 라우트 모듈에서만 읽는다).
import { after } from "next/server";

export function runInBackground(promise) {
  try {
    after(promise);
  } catch (e) {
    // 요청 범위 밖에서 불렸다 — 테스트·측정 스크립트가 라우트 핸들러를 직접 부르는 경우다.
    // 그때는 아무것도 안 해도 된다: 그 환경에는 함수 수명 제한이 없고, 약속은 이미 돌고 있다.
    //
    // ★ 삼키되 **말은 한다.** 프로덕션에서 이 자리가 던지면(예: 응답이 이미 끝난 뒤 호출)
    //   그것은 옛 결함으로 조용히 되돌아간 것이고, 로그가 없으면 아무도 모른다.
    if (process.env.NODE_ENV === "production") {
      console.error("background: after() 를 쓰지 못했다 — 이 작업은 응답 뒤에 끊길 수 있다:", e?.message);
    }
  }
  return promise;
}
