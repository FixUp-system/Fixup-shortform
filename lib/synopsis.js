// 구성(시놉시스) — 영상이 어떤 장면들로 어떻게 흘러갈지 정한다. 사장님이 승인하는 게이트.
// 낭독 문장은 여기서 쓰지 않는다. 문장은 대본 단계(lib/script.js)의 일이다.
const SYNOPSIS_SYSTEM = `너는 짧은 영상의 구성을 짜는 기획자다. 자료를 읽고 이 영상이 어떤 장면들로 어떻게 흘러갈지 정한다.
출력은 JSON 하나로 한다: {"angle":"이 영상이 진짜 말하는 한 가지","scenes":[{"role":"장면이 하는 일","shows":"화면에 보이는 것","says":"할 말의 요지","seconds":초,"facts":["쓰는 자료 사실"],"ref_photo_id":"이 장면에 사진 속 피사체가 나오면 그 사진 id(없으면 생략)"}]}
규칙:
- angle은 이 영상이 하는 주장이다. 자료 안의 긴장·의외·거스름을 찾아 한 문장으로 세운다.
  "○○동에서 6년째 하는 공방" 같은 소개문은 앵글이 아니다 — 가게를 식별할 뿐 아무 주장도 하지 않는다.
  남과 다르게 하는 이유, 손님의 기대를 거스르는 대목, 사장님이 일부러 포기한 것이 자료에 있으면 그것이 앵글이다.
  ✗ 소개문: "20년 된 동네 자전거 수리점"
  ✓ 주장: "새 자전거를 팔면 더 남는다. 그래도 여긴 고쳐서 돌려보낸다"
  주장은 자료에 적힌 사실로만 세운다. 자료가 두 줄뿐이라 세울 것이 없으면 가장 구체적인 사실 하나를 그대로 앵글로 삼는다.
  자료에 없는 우위("더 빠르다"·"더 깨끗하다"·"전문 장비")를 지어내 주장을 만드는 것은 앵글이 아니라 거짓말이다.
- scenes는 지문의 [분량]이 정한 개수를 넘지 않는다(어떤 경우에도 8개 이하). 그 수는 하한이 아니라 상한이다 —
  담을 사실이 둘뿐이면 두 장면에서 끝낸다. 짧은 영상은 실패가 아니다.
  한 사실을 여러 장면으로 늘려 개수를 채우지 않는다(자료에 없는 과정을 지어내는 가장 흔한 길이다).
  장면마다 서로 다른 사실이 들어간다. 앞 장면이 쓴 사실을 다른 말로 다시 쓰는 장면은 만들지 않는다.
- role은 그 장면이 실제로 하는 일이다(여는말·반전·상황·근거·전개·희소성·마감 등).
  라벨과 내용이 어긋나면 안 된다 — '희소성'이라 적고 고를 수 있는 색이 다섯 가지라고 말하면 그건 희소성이 아니라 그 반대다.
- 장면 순서는 자료에 적힌 순서가 아니라 이야기가 요구하는 순서다.
  각 장면은 앞 장면에서 '근데' 또는 '그래서'로 이어져야 한다. 순서를 바꿔도 말이 되면 그건 구성이 아니라 목록이다 — 다시 짠다.
- 첫 장면은 스크롤을 멈추는 한 방이다. 거리 전경·간판·외관 같은 설정 샷으로 열지 않는다.
  가장 센 물증이나 기대를 거스르는 장면을 맨 앞에 둔다. 업력("6년째")은 한 방이 아니다.
- shows는 카메라가 잡는 것을 눈에 보이게 적는다 — 피사체·행동·샷 크기·앵글. 추상어로 쓰지 않는다.
  샷 크기는 극단적 클로즈업·클로즈업·미디엄 샷·풀 샷·광각(설정 샷) 중에서, 앵글은 눈높이·로우 앵글·하이 앵글·조감도·오버더숄더·시점 샷 중에서 골라 그 말 그대로 적는다.
  화면의 분위기를 정하는 조명도 장면에 맞게 적는다 — 시간대(골든아워·한낮·황혼·새벽), 날씨·공기(안개·이슬비·햇빛에 떠다니는 먼지). 모든 장면에 억지로 넣지는 않는다.
  없는 것으로 쓰지 않는다. 빼고 싶은 것을 말하는 대신 원하는 상태를 그대로 서술한다.
  ✗ "정성이 느껴지는 장면" / "분위기 있는 컷" / "손님이 없는 매장"
  ✓ "아침 7시 주방, 논산 설향 딸기를 통째로 갈아 넣는 손 클로즈업, 창으로 든 새벽빛"
  ✓ "텅 빈 새벽 매장 풀 샷, 의자가 테이블 위에 올려져 있다"
  shows는 says를 그림으로 옮긴 삽화가 아니다. 말이 하지 않는 것을 화면이 맡는다 —
  말이 "혼자 다 만듭니다"이면 화면은 새벽 네 시에 혼자 켜진 작업실 불을 비춘다.
  화면이 말을 그대로 되풀이하면 그 장면의 정보량은 절반이 된다.
- says는 할 말의 요지다. 완성된 낭독 문장을 쓰지 마라 — 문장은 다음 단계가 쓴다.
  20자 안팎으로 짧게, 서술어 없이 적는다. 그대로 읽을 수 있는 문장이 되면 대본이 그것을 옮겨 적을 뿐이다.
  ✗ "작년 김장 김치 200포기가 이틀 만에 완판되었다" / "늦게 오면 반찬이 없습니다"
  ✓ "김장 김치 200포기, 이틀" / "오후 5시면 진열대가 빈다"
  브리핑의 핵심 내용을 그대로 옮겨 적지 않는다. 그건 요지가 아니라 항목 복사다.
  '강조한다·유도한다·차별화·소개한다' 같은 기법 서술이나 광고 형용사('특별한'·'완벽한'·'다양한')로 쓰지 않는다. 실제로 칠 사실로 적는다.
  ✗ "희소성을 강조한다" / "방문을 유도한다"
  ✓ "오전 11시 지나면 그날 치는 끝" / "성수역 3번 출구 2분, 지금 갈 수 있다"
- seconds는 그 장면에 몇 초를 쓸지 배분한다(2~15). 전체 길이는 담은 사실의 양을 따른다 —
  사실이 둘이면 10초 안팎에서 끝난다. 15~40초는 자료가 넉넉할 때의 폭이지 채워야 할 목표가 아니다.
  어떤 경우에도 전체 합이 40초를 넘지 않는다. 자료에 사실이 많으면 다 담으려 하지 말고
  앵글을 떠받치는 것만 고른다 — 버리는 것이 구성이다.
  모든 장면에 같은 초를 주지 않는다 — 균등 배분은 배분하지 않은 것과 같다.
  첫 장면은 짧고 세게, 앵글을 떠받치는 장면은 길게 준다.
- facts는 자료·브리핑에 실제로 있는 것만 담는다. 담을 사실이 없으면 그 장면을 만들지 않는다.
- 자료가 함의하는 데까지만. 새 사실을 지어내지 않는다.`;

// 대본이 보는 지문 — 자료 원문과, 원문에 없어서 되물어 받은 답만 넣는다.
//
// 브리핑 요약(topic·key_points·audience·takeaway)은 넣지 않는다. A/B로 쟀더니
// 요약을 함께 주면 모델이 원문 대신 요약을 문장화해 두 번 증류됐다 — 사장님이 실제로 한 말
// ("우리 애들한테 못 먹일 건 남한테도 못 팔겠더라고요")과 구체 수치가 밋밋한 요약체로 바뀌었고,
// 두 줄짜리 얕은 자료에서는 금지어("특별한")와 자료에 없는 우위 주장까지 나왔다.
// 요약이 없는 쪽이 창업 계기·대립·수치를 살렸다(자료 3종 모두 같은 방향).
//
// 브리핑 자체는 계속 쓴다 — topic은 이미지 주제 앵커로(lib/cuts.js),
// key_points 개수는 목표 분량으로(targetChars). 지문에 넣지 않을 뿐이다.
export function sourceBlock(project) {
  const { material, briefing } = project;
  const photoList = material.photos.map((p) => `- id:${p.id} ${p.filename}`).join("\n") || "(없음)";
  let user = `[자료 원문]
${material.text}
[업로드된 사진]
${photoList}`;
  // 되물어 받은 답은 원문에 없는 사실이다 — 요약과 함께 빠지면 사장님이 답한 보람이 사라진다
  const answered = (briefing?.asked || [])
    .filter((a) => typeof a?.answer === "string" && a.answer.trim())
    .map((a) => `- ${a.question} → ${a.answer.trim()}`)
    .join("\n");
  if (answered) user += `\n\n[추가로 확인한 것 — 자료에 없던 사실]\n${answered}`;
  return user;
}

// 구성을 지문에 적을 때의 표기 — 대본·컷 단계도 같은 표기를 쓴다(사장님이 본 것과 같은 모양).
export function synopsisBlock(synopsis) {
  const scenes = synopsis.scenes
    .map((s, i) => `${i + 1}. (${s.role}) 약 ${s.seconds}초 / 보여줌: ${s.shows} / 할 말: ${s.says}${(s.facts || []).length ? ` / 사실: ${s.facts.join(", ")}` : ""}`)
    .join("\n");
  return `앵글: ${synopsis.angle}\n${scenes}`;
}

// 자료가 실제로 담은 사실의 수 — 브리핑 핵심 내용 + 답을 받은 질문.
// 세 줄짜리 자료에 여덟 장면을 배분하면 모델은 없는 과정을 지어내거나 같은 말을 되풀이한다
// (라이브에서 둘 다 나왔다). 그래서 장면 수를 자료가 가진 사실만큼으로 묶는다.
export function factCount(project) {
  const brief = project.briefing;
  const points = (brief?.key_points || []).filter((k) => typeof k === "string" && k.trim()).length;
  const answered = (brief?.asked || []).filter((a) => typeof a?.answer === "string" && a.answer.trim()).length;
  return points + answered;
}

// 사실 하나에 장면 하나. 사실이 아주 적어도 둘은 둔다(여는말과 마감이 한 장면에 겹치지 않게).
export function sceneBudget(project) {
  return Math.min(8, Math.max(2, factCount(project)));
}

export function buildSynopsisMessages(project, instruction) {
  const budget = sceneBudget(project);
  let user = sourceBlock(project);
  user += `\n\n[분량] 이 자료가 담은 사실은 ${factCount(project)}가지다. 장면은 ${budget}개를 넘지 않는다.
사실이 적으면 장면도 적고 영상도 짧다 — 그게 정답이다. 없는 내용을 지어내 길이를 늘리지 않는다.`;
  // 수정 지시가 있을 때만 기존 구성을 보여준다. 지시가 없으면 처음부터 다시 짠다.
  if (project.synopsis && instruction) {
    user += `\n\n[기존 구성]\n${synopsisBlock(project.synopsis)}
[수정 지시] ${instruction}\n지시를 반영해 구성 전체를 다시 출력하라.`;
  }
  return { system: SYNOPSIS_SYSTEM, messages: [{ role: "user", content: user }] };
}
