// **운영자는 자기 역할을 못 바꾼다** (2026-09-01).
//
// ★★★ 왜 막나: 역할을 바꾸는 자리는 운영자 화면이고, 그 화면에 들어올 수 있는 사람은
//   운영자뿐이다. 마지막 운영자가 자기를 `user` 로 내리면 **그 순간 아무도 그 화면에
//   못 들어온다** — 되돌릴 문이 앱 안에 없고 DB 를 직접 고쳐야 한다.
//   승인·차단·등급에는 이 성질이 없다(자기를 차단해도 다른 운영자가 푼다).
//
// ★ **"마지막 운영자인가"를 세지 않는다.** 세려면 목록을 한 번 더 읽어야 하고, 두 요청이
//   동시에 들어오면 둘 다 "나 말고 또 있다"를 보고 통과해 아무도 안 남을 수 있다.
//   자기 것을 못 바꾸게 하면 그 경합이 아예 생기지 않는다 — 운영자를 내리려면 **다른
//   운영자**가 내려야 하고, 그러면 내리는 사람이 늘 하나는 남는다.
//
// ★ 값이 없으면 **안 막는다.** 없는 것 둘을 같다고 읽으면 남의 역할까지 못 바꾸게 된다.
export function blocksSelfRoleChange(actorId, targetId) {
  return !!actorId && !!targetId && actorId === targetId;
}
