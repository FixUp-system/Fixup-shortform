// **모델에게 보내는 영어 지문을 사장님 말로 옮긴다** (2026-09-03 사장님 지시).
//
// ★★ 왜 필요한가 — 시나리오·이미지 지문·영상 프롬프트가 전부 영어로만 보인다. 모델이
//   읽는 글이라 영어인 것은 맞지만, 사장님이 그것을 **확인하고 고치는 자리**이기도 하다.
//   지금은 사장님이 따로 번역기를 돌려야 무엇이 적혀 있는지 안다.
//
// ★★★ **원문은 절대 안 건드린다.** 번역은 곁들이는 값이고, 모델에게 나가는 것은 언제나
//   영어 원문이다. 각인(`of`)도 원문 하나를 문다 — 번역이 각인에 섞이면 번역이 달라질
//   때마다 이미 구운 편이 낡는다.
//
// ★ **앞으로 만드는 문서에만 붙는다**(사장님 결정). 옛 문서는 번역이 없고, 화면은
//   없으면 그 자리를 아예 안 그린다 — 옛 문서를 열 때 번역하려고 값을 쓰지 않는다.
//
// ★ 실패하면 **빈 값**이다. 번역이 안 되는 것과 지문을 못 만드는 것은 다른 일이라,
//   여기서 던져 본 일을 망치지 않는다(부르는 쪽이 `|| ""` 로 받는다).
import { callJson } from "./llm.js";

export const TRANSLATE_SYSTEM = `너는 영상 제작 지시문을 한국어로 옮기는 사람이다.

받는 글은 영상·이미지 생성 모델에게 주는 영어 지시문이다. 사장님이 **무엇이 적혀 있는지
확인하려고** 읽는다.

지켜야 할 것:
- **뜻을 그대로** 옮긴다. 요약하지도, 다듬지도, 빠뜨리지도 마라.
- 문단·줄바꿈 구조를 원문 그대로 지킨다.
- 따옴표 안의 **대사는 이미 한국어면 그대로 둔다** — 그것은 영상에서 실제로 말할 말이다.
- 제품명·브랜드·라벨에 인쇄된 글자는 **원문 그대로** 둔다(옮기면 딴 물건이 된다).
- 촬영 용어는 널리 쓰이는 우리말로 옮기되, 마땅한 말이 없으면 원어를 괄호로 남긴다.
- 옮긴 글만 돌려준다. "번역:" 같은 머리말이나 설명을 붙이지 마라.

JSON 하나만 출력한다: {"ko":"옮긴 글"}`;

const SCHEMA = {
  type: "object",
  properties: { ko: { type: "string" } },
  required: ["ko"],
  additionalProperties: false,
};

// 영어 지문 한 벌을 한국어로. 실패·빈 입력이면 **빈 문자열**이다.
//
// ★ 가짜 모드에서는 안 부른다 — 0원 관통이 이 자리에서 깨지지 않게(다른 LLM 호출과 같은 규약).
export async function translatePrompt(text, opts = {}) {
  const body = typeof text === "string" ? text.trim() : "";
  if (!body) return "";
  const call = opts.callJsonImpl || callJson;
  try {
    const out = await call({
      system: TRANSLATE_SYSTEM,
      messages: [{ role: "user", content: body }],
      schema: SCHEMA,
      stage: "지문 번역",
      projectId: opts.projectId,
      // ★ 가짜 모드에서는 **빈 값**이다(lib/reel/llm.js 의 `fake` 규약) — 그 모드가
      //   돌려주는 광고 시나리오가 여기 섞이면 번역 자리에 엉뚱한 글이 저장된다.
      fake: () => ({ ko: "" }),
    });
    return typeof out?.ko === "string" ? out.ko.trim() : "";
  } catch (e) {
    // ★ 삼키되 **말은 한다** — 조용히 비면 "왜 번역이 안 붙지"를 아무도 모른다.
    console.error("지문 번역 실패(원문은 그대로 쓴다):", e?.message);
    return "";
  }
}
